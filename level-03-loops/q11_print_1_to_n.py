# Question 11: Print Numbers 1 to N
# Problem Statement: Given an integer n, use a for loop and range() to print all numbers from 1 to n on the same line or line by line.
# Example Input: n = 5
# Example Output:
# text
# 1
# 2
# 3
# 4
# 5
# Concept Tested: for loop, range(start, stop)
# Difficulty: Beginner

n = int(input("Enter a number:"))

for i in range(1,n+1):
    print(i)


