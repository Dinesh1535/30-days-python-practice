# Question 4: Word Length and Shouting
# Problem Statement: Store a word in a variable text. Print the length of the word using len(), and print the word entirely in uppercase letters using .upper().
# Example Input: text = "python"
# Example Output:
# text
# Length: 6
# Uppercase: PYTHON
# Concept Tested: String methods, Built-in len() function
# Difficulty: Very Easy

text = input("Enter a text:")

print("Length: ",len(text))
print("Uppercase: ",text.upper())

